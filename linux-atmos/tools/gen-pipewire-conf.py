# Generates pipewire/atmos-headphones.conf.in (kept generated so the 11 near-identical
# spatializer blocks can't drift apart).
# Usage (from linux-atmos/): python3 tools/gen-pipewire-conf.py pipewire/atmos-headphones.conf.in
import sys
# PipeWire spatializer azimuth: 0 = front, 90 = left, 180 = behind, 270 = right.
speakers = [  # (port name, channel, azimuth, elevation, description)
    ("FL", 30, 0, "front left"), ("FR", 330, 0, "front right"), ("FC", 0, 0, "center"),
    ("RL", 135, 0, "rear surround left"), ("RR", 225, 0, "rear surround right"),
    ("SL", 90, 0, "side surround left"), ("SR", 270, 0, "side surround right"),
    ("TFL", 45, 45, "top front left"), ("TFR", 315, 45, "top front right"),
    ("TRL", 135, 45, "top rear left"), ("TRR", 225, 45, "top rear right"),
]
out = []
w = out.append
w("""# Atmos Headphones: 7.1.4 -> binaural virtual sink for PipeWire.
#
# This is the Linux counterpart of DolbyHrtfEnc.dll ("Dolby Atmos for Headphones") from
# Dolby Access: it takes a 7.1.4 speaker feed and renders each speaker through a head-related
# transfer function (HRTF), so headphones sound like a 7.1.4 room. Unlike Dolby's renderer it
# uses an open SOFA HRTF set, which you can swap for one that fits your ears better.
#
# Installed by install.sh, which substitutes the SOFA file path. Manual install:
#   cp atmos-headphones.conf ~/.config/pipewire/pipewire.conf.d/   (then restart pipewire)
#
# Speaker angles follow the Dolby 7.1.4 reference layout and match what atmos-decode renders:
# fronts +-30, sides +-90, rears +-135, top fronts +-45 / 45 up, top rears +-135 / 45 up.
#
# @generated by tools/gen-pipewire-conf.py - edit that script instead of this file.

context.modules = [
    { name = libpipewire-module-filter-chain
        flags = [ nofail ]
        args = {
            node.description = "Atmos Headphones (7.1.4 binaural)"
            media.name       = "Atmos Headphones (7.1.4 binaural)"
            filter.graph = {
                nodes = [""")
for name, az, el, desc in speakers:
    w(f"""                    # {desc}
                    {{
                        type = sofa
                        label = spatializer
                        name = sp{name}
                        config = {{
                            filename = "@SOFA_FILE@"
                            # The right gain depends on the .sofa file in use
                            gain = @HRTF_GAIN@
                        }}
                        control = {{
                            "Azimuth"   = {az:.1f}
                            "Elevation" = {el:.1f}
                            # Keep Radius last and != 1.0: PipeWire <= 1.0.x only loads the HRTF
                            # if the last control set differs from its default.
                            "Radius"    = @HRTF_RADIUS@
                        }}
                    }}""")
w("""                    # LFE has no direction: feed it to both ears equally
                    { type = builtin label = copy name = lfe }

                    # Mixers take at most 8 inputs, so each ear sums in two stages
                    { type = builtin label = mixer name = mixL1 }
                    { type = builtin label = mixer name = mixR1 }
                    { type = builtin label = mixer name = mixL2
                        control = { "Gain 5" = @LFE_GAIN@ }
                    }
                    { type = builtin label = mixer name = mixR2
                        control = { "Gain 5" = @LFE_GAIN@ }
                    }
                ]
                links = [""")
first, second = speakers[:8], speakers[8:]
for i, (name, *_ ) in enumerate(first, 1):
    w(f'                    {{ output = "sp{name}:Out L" input = "mixL1:In {i}" }}')
    w(f'                    {{ output = "sp{name}:Out R" input = "mixR1:In {i}" }}')
w('                    { output = "mixL1:Out" input = "mixL2:In 1" }')
w('                    { output = "mixR1:Out" input = "mixR2:In 1" }')
for i, (name, *_ ) in enumerate(second, 2):
    w(f'                    {{ output = "sp{name}:Out L" input = "mixL2:In {i}" }}')
    w(f'                    {{ output = "sp{name}:Out R" input = "mixR2:In {i}" }}')
w('                    { output = "lfe:Out" input = "mixL2:In 5" }')
w('                    { output = "lfe:Out" input = "mixR2:In 5" }')
order = ["FL", "FR", "FC", "LFE", "RL", "RR", "SL", "SR", "TFL", "TFR", "TRL", "TRR"]
inputs = " ".join('"lfe:In"' if c == "LFE" else f'"sp{c}:In"' for c in order)
w(f"""                ]
                inputs  = [ {inputs} ]
                outputs = [ "mixL2:Out" "mixR2:Out" ]
            }}
            capture.props = {{
                node.name      = "effect_input.atmos_headphones"
                media.class    = Audio/Sink
                audio.channels = 12
                audio.position = [ {" ".join(order)} ]
            }}
            playback.props = {{
                node.name      = "effect_output.atmos_headphones"
                node.passive   = true
                audio.channels = 2
                audio.position = [ FL FR ]
            }}
        }}
    }}
]""")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
